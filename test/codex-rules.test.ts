import { vaultRoot } from "./setup.js";
import { test } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { SERVER_INSTRUCTIONS } from "../src/server.js";

/** The Codex rules block (AGENTS.md / AGENTS.override.md) written by hooks/install-hook.mjs, against throwaway CODEX_HOMEs. */

const script = fileURLToPath(new URL("../hooks/install-hook.mjs", import.meta.url));
const hookPath = fileURLToPath(new URL("../hooks/librarian-stop.sh", import.meta.url));
const built = fs.existsSync(fileURLToPath(new URL("../dist/capture-cli.js", import.meta.url)));
const t = built ? test : test.skip;
const BEGIN = "<!-- BEGIN rutter-capture-rule: generated by install-hook; edits inside this block are overwritten on re-run -->";
const END = "<!-- END rutter-capture-rule -->";

let n = 0;
function sandbox() {
  const home = path.join(vaultRoot, `codex-rules-${n++}`);
  const codexHome = path.join(home, ".codex");
  fs.mkdirSync(codexHome, { recursive: true });
  return {
    home,
    codexHome,
    hooks: path.join(codexHome, "hooks.json"),
    agents: path.join(codexHome, "AGENTS.md"),
    override: path.join(codexHome, "AGENTS.override.md"),
  };
}
function install(sb: { home: string; codexHome: string }, ...args: string[]) {
  const res = spawnSync(process.execPath, [script, "--client", "codex", ...args], {
    env: { ...process.env, HOME: sb.home, CODEX_HOME: sb.codexHome, LIBRARIAN_VAULT_PATH: "/v/notes" },
    encoding: "utf8",
  });
  return { status: res.status, stderr: res.stderr };
}
const read = (f: string) => fs.readFileSync(f, "utf8");
const count = (s: string, needle: string) => s.split(needle).length - 1;
const writeHooks = (sb: { hooks: string }, command: string) =>
  fs.writeFileSync(sb.hooks, JSON.stringify({ hooks: { Stop: [{ hooks: [{ type: "command", command, timeout: 30 }] }] } }), "utf8");

t("a new AGENTS.md gets one block carrying the server's own instructions; a re-run changes nothing", () => {
  const sb = sandbox();
  const first = install(sb);
  assert.equal(first.status, 0, first.stderr);
  const body = read(sb.agents);
  assert.equal(count(body, BEGIN), 1);
  assert.equal(count(body, END), 1);
  assert.ok(body.includes(SERVER_INSTRUCTIONS.trim()), "the whole server contract, routing and capture, is in the block (SR-027)");
  assert.match(first.stderr, /wrote .*AGENTS\.md/);
  const again = install(sb);
  assert.equal(read(sb.agents), body);
  assert.match(again.stderr, /already up to date/);
});

t("other content in AGENTS.md is kept byte for byte, and a stale block is replaced in place", () => {
  const sb = sandbox();
  const mine = "# My rules\n\nBe brief.\n";
  fs.writeFileSync(sb.agents, mine, "utf8");
  assert.equal(install(sb).status, 0);
  const withBlock = read(sb.agents);
  assert.ok(withBlock.startsWith(mine), "existing bytes untouched");
  fs.writeFileSync(sb.agents, withBlock.replace(/This user keeps a record/, "STALE"), "utf8");
  const res = install(sb);
  assert.match(res.stderr, /updated the rutter block/);
  assert.equal(read(sb.agents), withBlock);
  assert.equal(count(read(sb.agents), BEGIN), 1);
});

t("an ambiguous AGENTS.md is refused and nothing is written, hooks.json included", () => {
  for (const bad of [`${BEGIN}\nx\n${BEGIN}\ny\n${END}\n`, `\`\`\`\n${BEGIN}\n${END}\n\`\`\`\n`]) {
    const sb = sandbox();
    fs.writeFileSync(sb.agents, bad, "utf8");
    const res = install(sb);
    assert.equal(res.status, 1);
    assert.match(res.stderr, /nothing was changed/);
    assert.equal(read(sb.agents), bad);
    assert.equal(fs.existsSync(sb.hooks), false, "no hook registered either");
  }
});

t("a nonempty AGENTS.override.md without a block is refused with its path and the --no-rules hint; an empty one is ignored", () => {
  const sb = sandbox();
  fs.writeFileSync(sb.override, "my override\n", "utf8");
  const res = install(sb);
  assert.equal(res.status, 1);
  assert.ok(res.stderr.includes(sb.override));
  assert.match(res.stderr, /--no-rules/);
  assert.equal(fs.existsSync(sb.hooks), false);
  assert.equal(fs.existsSync(sb.agents), false);

  const empty = sandbox();
  fs.writeFileSync(empty.override, "", "utf8");
  assert.equal(install(empty).status, 0);
  assert.equal(read(empty.override), "", "the empty override is left alone");
  assert.equal(count(read(empty.agents), BEGIN), 1);
});

t("--no-rules installs the hook and no rules file; once the block is in the override, a re-run refreshes it there only", () => {
  const sb = sandbox();
  fs.writeFileSync(sb.override, "my override\n", "utf8");
  const res = install(sb, "--no-rules");
  assert.equal(res.status, 0, res.stderr);
  assert.equal(fs.existsSync(sb.hooks), true);
  assert.equal(fs.existsSync(sb.agents), false);
  assert.equal(read(sb.override), "my override\n");

  fs.writeFileSync(sb.override, `my override\n\n${BEGIN}\nstale\n${END}\n`, "utf8");
  assert.equal(install(sb).status, 0);
  assert.ok(read(sb.override).includes(SERVER_INSTRUCTIONS.trim()), "refreshed in the override");
  assert.ok(read(sb.override).startsWith("my override\n"));
  assert.equal(fs.existsSync(sb.agents), false, "AGENTS.md left alone");
});

t("--no-rules is Codex-only", () => {
  const sb = sandbox();
  const res = spawnSync(process.execPath, [script, "--client", "claude", "--no-rules"], { env: { ...process.env, HOME: sb.home }, encoding: "utf8" });
  assert.equal(res.status, 1);
});

t("an existing hook (unchanged, custom, or outdated) still gets the block, and a current block is left alone", () => {
  const cases: Record<string, string> = {
    unchanged: `LIBRARIAN_VAULT_PATH="\${LIBRARIAN_VAULT_PATH:-/v/notes}" ${hookPath} --client codex`,
    custom: `${hookPath} --client codex && my-audit`,
    outdated: `/old/place/hooks/librarian-stop.sh --client codex`,
  };
  for (const [name, command] of Object.entries(cases)) {
    const sb = sandbox();
    writeHooks(sb, command);
    const res = install(sb);
    assert.equal(res.status, 0, `${name}: ${res.stderr}`);
    const body = read(sb.agents);
    assert.equal(count(body, BEGIN), 1, name);
    const hooksAfter = read(sb.hooks);
    assert.equal(install(sb).status, 0);
    assert.equal(read(sb.agents), body, `${name}: current block unchanged`);
    assert.equal(read(sb.hooks), hooksAfter, `${name}: hooks stable`);
  }
});

t("an inline config.toml hook still stops everything, the rules file included", () => {
  const sb = sandbox();
  fs.writeFileSync(path.join(sb.codexHome, "config.toml"), `[[hooks.Stop]]\ncommand = "${hookPath}"\n`, "utf8");
  const res = install(sb);
  assert.equal(res.status, 1);
  assert.equal(fs.existsSync(sb.agents), false);
  assert.equal(fs.existsSync(sb.hooks), false);
});

t("a refused --vault on a custom hook writes no rules, and a failed hook write leaves no rules behind", () => {
  const custom = sandbox();
  writeHooks(custom, `${hookPath} --client codex && my-audit`);
  const res = install(custom, "--vault", "");
  assert.equal(res.status, 1);
  assert.equal(fs.existsSync(custom.agents), false);

  const blocked = sandbox();
  fs.mkdirSync(`${blocked.hooks}.librarian-tmp`);
  assert.equal(install(blocked).status === 0, false, "the hook write fails");
  assert.equal(fs.existsSync(blocked.agents), false, "no rules block without a hook");
});
